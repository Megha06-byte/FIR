#!/usr/bin/env python3
"""
fir_model.py : FIR design + bit-exact fixed-point golden model.

Filter    : 31-tap linear-phase low-pass, Hamming window (scipy.firwin)
            fs = 48 kHz, cutoff 6 kHz
Fixed pt  : input  x  int16 Q1.15
            coeffs c  int16 Q1.15 (rounded)
            output y  int16 Q1.15:  y = sat16((sum c[k] x[n-k] + 2^14) >> 15)
Test sig  : 1 kHz + 3 kHz (wanted) + 14 kHz + 19 kHz interferers + white noise

Writes:
  rtl/fir_coeffs.vh   localparam coefficient vector (shared by all RTL variants)
  sim/x.hex, sim/y_gold.hex   stimulus + expected output (signal + impulse + random)
  results/dsp_metrics.json    SNR / quantisation numbers
  results/response.png        frequency response + time-domain plot
"""
import os, json
import numpy as np
from scipy import signal

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
N, FS, FC = 31, 48_000, 6_000
CW, XW = 16, 16                    # coefficient / sample width
FRAC = 15
rng = np.random.default_rng(0)

# ------------------------------------------------------------------ design
h = signal.firwin(N, FC, window="hamming", fs=FS)
cq = np.round(h * (1 << FRAC)).astype(np.int64)
assert np.all(cq == cq[::-1]), "linear-phase filter must be symmetric"
assert np.abs(cq).max() < (1 << (CW - 1))

# ------------------------------------------------------------------ stimulus
L = 4096
t = np.arange(L) / FS
clean = 0.30 * np.sin(2*np.pi*1000*t) + 0.20 * np.sin(2*np.pi*3000*t)
interf = 0.20 * np.sin(2*np.pi*14000*t) + 0.15 * np.sin(2*np.pi*19000*t)
noise = 0.05 * rng.standard_normal(L)
noisy = clean + interf + noise

def to_q15(v):
    return np.clip(np.round(v * (1 << FRAC)), -32768, 32767).astype(np.int64)

def fir_fixed(xq):
    """bit-exact model of the RTL"""
    acc = np.convolve(xq, cq)[:len(xq)]
    y = (acc + (1 << (FRAC - 1))) >> FRAC
    return np.clip(y, -32768, 32767)

# extra verification vectors: impulse (y must equal coeffs), step, full-scale random
impulse = np.zeros(64, np.int64); impulse[0] = 32767
step = np.full(64, 32767, np.int64)
randv = rng.integers(-32768, 32768, 2048)
xq_sig = to_q15(noisy)
x_all = np.concatenate([xq_sig, impulse, -step, randv])
y_all = fir_fixed(x_all)

# ------------------------------------------------------------------ metrics
D = (N - 1) // 2                       # group delay of linear-phase FIR
def snr(ref, test):
    ref, test = ref[D + N:], test[D + N:]   # skip start-up transient
    return 10 * np.log10(np.sum(ref**2) / np.sum((test - ref)**2))

clean_d = np.concatenate([np.zeros(D), clean])[:L]
y_float = signal.lfilter(h, 1.0, noisy)
y_fix = fir_fixed(xq_sig) / (1 << FRAC)
metrics = dict(
    taps=N, fs=FS, fc=FC,
    snr_in_db=float(snr(clean, noisy)),
    snr_out_float_db=float(snr(clean_d, y_float)),
    snr_out_fixed_db=float(snr(clean_d, y_fix)),
    quant_snr_db=float(10*np.log10(np.sum(y_float[N:]**2) /
                                   np.sum((y_fix[N:] - y_float[N:])**2))),
)
w, H = signal.freqz(h, worN=4096, fs=FS)
_, Hq = signal.freqz(cq / (1 << FRAC), worN=4096, fs=FS)
sb = w >= 9000
metrics["stopband_atten_float_db"] = float(-20*np.log10(np.abs(H[sb]).max()))
metrics["stopband_atten_fixed_db"] = float(-20*np.log10(np.abs(Hq[sb]).max()))
metrics["unique_coeffs"] = int((N + 1) // 2)

# ------------------------------------------------------------------ export
with open(os.path.join(ROOT, "rtl", "fir_coeffs.vh"), "w") as f:
    f.write("// generated by model/fir_model.py -- do not edit\n")
    f.write(f"// {N}-tap Hamming low-pass, fs={FS} Hz, fc={FC} Hz, Q1.15\n")
    f.write(f"localparam integer NTAP = {N};\n")
    word = 0
    for k, v in enumerate(cq):
        word |= (int(v) & 0xffff) << (16 * k)
    f.write(f"localparam [{16*N-1}:0] COEF = {16*N}'h{word:0{4*N}x};\n")

with open(os.path.join(ROOT, "sim", "x.hex"), "w") as f:
    f.write("\n".join(f"{int(v) & 0xffff:04x}" for v in x_all) + "\n")
with open(os.path.join(ROOT, "sim", "y_gold.hex"), "w") as f:
    f.write("\n".join(f"{int(v) & 0xffff:04x}" for v in y_all) + "\n")
with open(os.path.join(ROOT, "sim", "nsamp.vh"), "w") as f:
    f.write(f"`define NSAMP {len(x_all)}\n")
json.dump(metrics, open(os.path.join(ROOT, "results", "dsp_metrics.json"), "w"), indent=1)

try:
    import matplotlib; matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(2, 1, figsize=(8, 6))
    ax[0].plot(w/1e3, 20*np.log10(np.abs(H)+1e-12), label="float")
    ax[0].plot(w/1e3, 20*np.log10(np.abs(Hq)+1e-12), "--", label="Q1.15")
    ax[0].set(xlabel="kHz", ylabel="dB", ylim=(-100, 5), title="Magnitude response")
    ax[0].legend(); ax[0].grid(alpha=.3)
    s = slice(600, 800)
    ax[1].plot(t[s]*1e3, noisy[s], alpha=.5, label="noisy input")
    ax[1].plot(t[s]*1e3, y_fix[s], label="RTL output (fixed)")
    ax[1].plot(t[s]*1e3, clean_d[s], ":", label="clean (delayed)")
    ax[1].set(xlabel="ms"); ax[1].legend(); ax[1].grid(alpha=.3)
    fig.tight_layout(); fig.savefig(os.path.join(ROOT, "results", "response.png"), dpi=120)
except ImportError:
    pass

print(json.dumps(metrics, indent=1))
print("coeffs:", cq.tolist())
